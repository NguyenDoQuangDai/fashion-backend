-- Additive M1: never update inventory values.
ALTER TABLE product_size_variants ADD COLUMN inventory_revision bigint NOT NULL DEFAULT 0;
ALTER TABLE product_size_variants ADD CONSTRAINT inventory_nonnegative CHECK (inventory IS NULL OR inventory >= 0);
CREATE TABLE stock_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 size_variant_id bigint NOT NULL REFERENCES product_size_variants(id) ON DELETE RESTRICT,
 operation_key varchar(200) NOT NULL,
 kind varchar(40) NOT NULL,
 before_inventory integer NOT NULL,
 delta integer NOT NULL,
 after_inventory integer NOT NULL CHECK (after_inventory >= 0),
 revision bigint NOT NULL CHECK (revision > 0),
 actor text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(size_variant_id, operation_key),
 UNIQUE(size_variant_id, revision),
 CHECK (after_inventory::bigint = before_inventory::bigint + delta::bigint)
);
CREATE INDEX stock_movements_operation_idx ON stock_movements(operation_key);
ALTER TABLE order_items ADD COLUMN size_variant_id bigint REFERENCES product_size_variants(id) ON DELETE RESTRICT;
-- Historical order snapshots remain unchanged. Resolve legacy mappings under locks on restore.

-- Audit rows cannot be edited or deleted by application mistakes.
CREATE FUNCTION reject_stock_movement_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'stock_movements is append-only';
END;
$$;
CREATE TRIGGER stock_movements_append_only BEFORE UPDATE OR DELETE ON stock_movements
 FOR EACH ROW EXECUTE FUNCTION reject_stock_movement_mutation();
